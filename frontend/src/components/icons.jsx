// Professional line icons (inline SVG, single colour, no emoji).
// Every icon inherits the surrounding text colour via currentColor, so
// sidebar, buttons and headings all stay visually consistent.

function Svg({ children, size = 18, ...props }) {
  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="2"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  )
}

